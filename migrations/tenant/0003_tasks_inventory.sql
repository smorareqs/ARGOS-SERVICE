-- Tareas e inventario (APP/docs/plans/fase02.md §2, parte de Persona B).
--
-- Diferencias con el plan (para que el portal web de Persona A y la app usen
-- el mismo contrato, avance.md):
-- * `tasks.type` conserva el tipo grueso del plan ('cleaning', 'inspection',
--   'maintenance', 'checkout_review'), que es lo que lee la nomina
--   (payroll: type = 'cleaning' AND status = 'validated'). `tasks.kind` es el
--   tipo fino que muestran la web y la app: checkout_cleaning, deep_cleaning y
--   touch_up son limpiezas; inspection y maintenance coinciden con su tipo.
-- * `tasks.status`: 'done' en lugar de 'completed' y un estado 'returned'
--   (el supervisor la devolvio con motivo; se sigue trabajando).
-- * `tasks.priority` es 'normal' o 'high' (asi la muestra la web).
-- * `tasks.number`: folio corto por empresa ("#128") como las incidencias.
-- * `tasks.reservation_id` y `tasks.maintenance_ticket_id` no tienen FK aqui:
--   0004 y 0006 crean las de las otras tablas hacia `tasks` y la de
--   reservation_id.
-- * `inventory_items.category` usa las categorias de la web (linens,
--   amenities, cleaning, kitchen, keys) y `returnable` dice si al cerrar una
--   tarea se devuelve todo (blancos, llaves) o se puede consumir.
-- * `inventory_movements.type` usa los nombres de la web: entry, checkout,
--   return, transfer, adjustment, consumption. En ajustes la cantidad puede
--   ser negativa; en los demas es positiva.
-- * `restock_requests` tiene sus articulos en `restock_request_items` (una
--   solicitud pide varios) y el estado inicial es 'pending'.

