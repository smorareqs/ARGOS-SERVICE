CREATE TABLE tasks (
    id                    uuid         NOT NULL DEFAULT gen_random_uuid(),
    number                integer      GENERATED BY DEFAULT AS IDENTITY,
    property_id           uuid         NOT NULL,
    type                  varchar(24)  NOT NULL,
    kind                  varchar(24)  NOT NULL,
    status                varchar(16)  NOT NULL DEFAULT 'pending',
    priority              varchar(8)   NOT NULL DEFAULT 'normal',
    scheduled_date        date         NOT NULL,
    window_start          time,
    window_end            time,
    assigned_to           uuid,
    assigned_by           uuid,
    created_by            uuid,
    reservation_id        uuid,
    maintenance_ticket_id uuid,
    checklist_template_id uuid,
    started_at            timestamptz,
    finished_at           timestamptz,
    start_lat             numeric(9,6),
    start_lng             numeric(9,6),
    end_lat               numeric(9,6),
    end_lng               numeric(9,6),
    validated_by          uuid,
    validated_at          timestamptz,
    is_late               boolean      NOT NULL DEFAULT false,
    notes                 text,
    completion_notes      text,
    created_at            timestamptz  NOT NULL DEFAULT now(),
    updated_at            timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_tasks PRIMARY KEY (id),
    CONSTRAINT uq_tasks_number UNIQUE (number),
    CONSTRAINT fk_tasks_property_id_properties FOREIGN KEY (property_id) REFERENCES properties (id),
    CONSTRAINT fk_tasks_assigned_to_users FOREIGN KEY (assigned_to) REFERENCES shared.users (id) ON DELETE SET NULL,
    CONSTRAINT fk_tasks_assigned_by_users FOREIGN KEY (assigned_by) REFERENCES shared.users (id) ON DELETE SET NULL,
    CONSTRAINT fk_tasks_created_by_users FOREIGN KEY (created_by) REFERENCES shared.users (id) ON DELETE SET NULL,
    CONSTRAINT fk_tasks_validated_by_users FOREIGN KEY (validated_by) REFERENCES shared.users (id) ON DELETE SET NULL,
    CONSTRAINT fk_tasks_checklist_template_id_checklist_templates FOREIGN KEY (checklist_template_id)
        REFERENCES checklist_templates (id) ON DELETE SET NULL,
    CONSTRAINT ck_tasks_type CHECK (type IN ('cleaning', 'inspection', 'maintenance', 'checkout_review')),
    CONSTRAINT ck_tasks_kind CHECK (kind IN ('checkout_cleaning', 'deep_cleaning', 'touch_up', 'inspection', 'maintenance')),
    CONSTRAINT ck_tasks_status CHECK (status IN ('pending', 'in_progress', 'done', 'validated', 'returned', 'cancelled')),
    CONSTRAINT ck_tasks_priority CHECK (priority IN ('normal', 'high')),
    CONSTRAINT ck_tasks_window CHECK (window_start IS NULL OR window_end IS NULL OR window_start < window_end)
);
CREATE INDEX ix_tasks_scheduled_date ON tasks (scheduled_date);
CREATE INDEX ix_tasks_assigned_to ON tasks (assigned_to, scheduled_date);
CREATE INDEX ix_tasks_property_id ON tasks (property_id, scheduled_date);
CREATE INDEX ix_tasks_status ON tasks (status);
CREATE INDEX ix_tasks_updated_at ON tasks (updated_at);
-- Una limpieza de salida por reserva (generate-from-reservations no duplica).
CREATE UNIQUE INDEX uq_tasks_reservation_kind ON tasks (reservation_id, kind)
    WHERE reservation_id IS NOT NULL AND status <> 'cancelled';

