CREATE TABLE warehouses (
    id          uuid         NOT NULL DEFAULT gen_random_uuid(),
    name        varchar(128) NOT NULL,
    property_id uuid,
    is_active   boolean      NOT NULL DEFAULT true,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_warehouses PRIMARY KEY (id),
    CONSTRAINT fk_warehouses_property_id_properties FOREIGN KEY (property_id) REFERENCES properties (id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX uq_warehouses_property_id ON warehouses (property_id) WHERE property_id IS NOT NULL;
CREATE UNIQUE INDEX uq_warehouses_name ON warehouses (lower(name));

CREATE TABLE inventory_items (
    id         uuid          NOT NULL DEFAULT gen_random_uuid(),
    sku        varchar(32),
    name       varchar(128)  NOT NULL,
    category   varchar(16)   NOT NULL,
    unit       varchar(16)   NOT NULL DEFAULT 'unidad',
    min_stock  numeric(12,3) NOT NULL DEFAULT 0,
    returnable boolean       NOT NULL DEFAULT false,
    is_active  boolean       NOT NULL DEFAULT true,
    created_at timestamptz   NOT NULL DEFAULT now(),
    updated_at timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_inventory_items PRIMARY KEY (id),
    CONSTRAINT ck_inventory_items_category CHECK (category IN ('linens', 'amenities', 'cleaning', 'kitchen', 'keys')),
    CONSTRAINT ck_inventory_items_min_stock CHECK (min_stock >= 0)
);
CREATE UNIQUE INDEX uq_inventory_items_sku ON inventory_items (upper(sku)) WHERE sku IS NOT NULL;

CREATE TABLE inventory_stock (
    warehouse_id uuid          NOT NULL,
    item_id      uuid          NOT NULL,
    quantity     numeric(12,3) NOT NULL DEFAULT 0,
    updated_at   timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT pk_inventory_stock PRIMARY KEY (warehouse_id, item_id),
    CONSTRAINT fk_inventory_stock_warehouse_id_warehouses FOREIGN KEY (warehouse_id) REFERENCES warehouses (id) ON DELETE CASCADE,
    CONSTRAINT fk_inventory_stock_item_id_inventory_items FOREIGN KEY (item_id) REFERENCES inventory_items (id) ON DELETE CASCADE,
    CONSTRAINT ck_inventory_stock_quantity CHECK (quantity >= 0)
);
CREATE INDEX ix_inventory_stock_item_id ON inventory_stock (item_id);

